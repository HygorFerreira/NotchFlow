import AppKit
import Combine

struct ClipboardEntry: Identifiable, Equatable {
    let id = UUID()
    let text: String?
    let image: Data?
    let date = Date()
    var preview: String { text ?? String(localized: "Copied image") }
}

@MainActor
final class ClipboardMonitor: ObservableObject {
    @Published private(set) var entries: [ClipboardEntry] = []
    @Published private(set) var enabled: Bool
    @Published private(set) var copiedID: UUID?
    private let pasteboard: NSPasteboard
    private let defaults: UserDefaults
    private var changeCount: Int
    private var timer: AnyCancellable?
    static let ignoredTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                               "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]

    init(pasteboard: NSPasteboard = .general, defaults: UserDefaults = .standard, start: Bool = true) {
        self.pasteboard = pasteboard
        self.defaults = defaults
        enabled = start && defaults.bool(forKey: "clipboard.enabled")
        changeCount = pasteboard.changeCount
        if start {
            timer = Timer.publish(every: 1, on: .main, in: .common).autoconnect()
                .sink { [weak self] _ in self?.poll() }
        }
    }

    func setEnabled(_ value: Bool) {
        changeCount = pasteboard.changeCount
        enabled = value
        defaults.set(value, forKey: "clipboard.enabled")
        if !value { clear() }
    }

    func poll() {
        guard enabled, pasteboard.changeCount != changeCount else { return }
        changeCount = pasteboard.changeCount
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.ignoredTypes), !types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) else { return }
        let entry: ClipboardEntry
        if let text = pasteboard.string(forType: .string), !text.isEmpty, text.utf8.count <= 100_000 {
            entry = ClipboardEntry(text: text, image: nil)
        } else if let image = pasteboard.data(forType: .png), image.count <= 5_000_000 {
            entry = ClipboardEntry(text: nil, image: image)
        } else { return }
        entries.removeAll { $0.text == entry.text && $0.image == entry.image }
        entries.insert(entry, at: 0)
        entries = Array(entries.prefix(30))
        copiedID = nil
    }

    func copy(_ entry: ClipboardEntry) {
        pasteboard.clearContents()
        if let text = entry.text { pasteboard.setString(text, forType: .string) }
        else if let image = entry.image { pasteboard.setData(image, forType: .png) }
        changeCount = pasteboard.changeCount
        copiedID = entry.id
    }

    func remove(_ id: UUID) { entries.removeAll { $0.id == id } }
    func clear() { entries = []; copiedID = nil }

    #if DEBUG
    func setDemo() {
        timer?.cancel()
        enabled = true
        entries = [ClipboardEntry(text: "Ideias para a próxima sessão de foco", image: nil),
                   ClipboardEntry(text: "https://example.com/projeto", image: nil)]
    }
    #endif
}
